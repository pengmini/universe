/* 실제 글이 하나도 없는 주제에만 예시를 얹는다 */
export function withDemo(real, on){
  if (!on) return real;
  const busy = new Set(real.map(s => s.topic));
  return [...real, ...DEMO.filter(d => !busy.has(d.topic))];
}
